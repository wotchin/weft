/**
 * DiagramGenerator — generate diagrams from content using LLM.
 *
 * Supports multiple diagram types via Mermaid syntax:
 *   flowchart, mindmap, sequence, timeline, pie, classDiagram, erDiagram
 *
 * Also supports direct SVG generation for custom illustrations.
 *
 * The LLM receives content + desired diagram type and returns Mermaid code.
 * Rendering is handled by sandbox-mermaid.html (sandboxed iframe with Mermaid.js).
 */
/* exported DiagramGenerator */
/* global LLMClient */
const DiagramGenerator = (() => {

    // Supported diagram types with descriptions
    const DIAGRAM_TYPES = [
        { id: 'auto',      label: 'Auto-detect',       desc: 'LLM chooses the best diagram type' },
        { id: 'flowchart', label: 'Flowchart',          desc: 'Process flows, decision trees, algorithms' },
        { id: 'mindmap',   label: 'Mind Map',           desc: 'Topic overview, concept relationships' },
        { id: 'sequence',  label: 'Sequence Diagram',   desc: 'Interactions between entities' },
        { id: 'timeline',  label: 'Timeline',           desc: 'Chronological events, history' },
        { id: 'pie',       label: 'Pie Chart',          desc: 'Data distribution' },
        { id: 'classDiagram', label: 'Class Diagram',   desc: 'Structures, relationships, hierarchies' },
        { id: 'erDiagram', label: 'ER Diagram',         desc: 'Entity relationships' },
        { id: 'quadrant',  label: 'Quadrant Chart',     desc: '2x2 matrix, comparison' },
        { id: 'svg',       label: 'Custom SVG',         desc: 'Free-form illustration generated by LLM' },
    ];

    /**
     * Auto-detect the best diagram type based on content.
     */
    function detectDiagramType(text) {
        if (!text) return 'mindmap';
        const t = text.toLowerCase();

        // Data/percentages → pie chart
        if ((t.match(/\d+(\.\d+)?%/g) || []).length >= 3) return 'pie';
        // Dates/years → timeline
        if ((t.match(/\b(19|20)\d{2}\b/g) || []).length >= 3) return 'timeline';
        if (/\d{4}年/.test(t) && (t.match(/\d{4}年/g) || []).length >= 3) return 'timeline';
        // Step/process words → flowchart
        if (/\b(step|then|next|first|finally|process|flow|if.*then)\b/i.test(t)) return 'flowchart';
        if (/步骤|流程|首先|然后|接着|最后/.test(t)) return 'flowchart';
        // Interaction words → sequence
        if (/\b(request|response|send|receive|call|return|API)\b/i.test(t)) return 'sequence';
        if (/请求|响应|发送|接收|调用|返回/.test(t)) return 'sequence';
        // Comparison → quadrant
        if (/\b(vs|versus|compare|advantage|disadvantage|pros|cons)\b/i.test(t)) return 'quadrant';
        // Default → mindmap
        return 'mindmap';
    }

    /**
     * Build the LLM prompt to generate a Mermaid diagram.
     */
    function buildDiagramPrompt(content, diagramType, userQuery, language) {
        // Accepts either a legacy short code or a language name; labels follow
        // the user's chosen language, not the source material's.
        const lang = language === 'zh' ? 'Simplified Chinese'
            : (language === 'en' || !language) ? 'English'
                : language;
        const type = diagramType === 'auto' ? detectDiagramType(content) : diagramType;

        if (type === 'svg') {
            return {
                type: 'svg',
                prompt: buildSvgPrompt(content, userQuery, lang),
            };
        }

        const typeHints = {
            flowchart: 'Use `flowchart TD` (top-down) or `flowchart LR` (left-right). Use descriptive labels on nodes and edges. Use decision diamonds `{...}` where appropriate.',
            mindmap: 'Use `mindmap` syntax. Create a clear hierarchy with the main topic as root. Use meaningful subtopics.',
            sequence: 'Use `sequenceDiagram`. Show interactions between participants. Use arrows (->, -->>, ->>>) for different message types.',
            timeline: 'Use `timeline` syntax. List events chronologically with clear date/period labels.',
            pie: 'Use `pie title "..."` syntax. Extract numerical data from the content.',
            classDiagram: 'Use `classDiagram`. Show classes/entities with attributes and relationships (+, -, #).',
            erDiagram: 'Use `erDiagram`. Show entities and their relationships (one-to-many, many-to-many, etc.).',
            quadrant: 'Use `quadrantChart`. Define axis labels and position items in the 4 quadrants.',
        };

        let prompt = `Generate a Mermaid diagram from the following content.

Diagram type: ${type}
${typeHints[type] || ''}

Rules:
1. Output ONLY the Mermaid code block — no explanation, no markdown fences
2. Use ${lang} labels in the diagram
3. Keep labels concise (max 30 chars per label)
4. Ensure valid Mermaid syntax
5. Make the diagram informative and clear
6. If the content doesn't have enough information for the requested diagram type, adapt the type to what works best
`;

        if (userQuery) {
            prompt += `\nUser's specific request: ${userQuery}\n`;
        }

        prompt += `\nContent to visualize:\n${content.substring(0, 8000)}\n`;

        return { type, prompt };
    }

    /**
     * Build prompt for direct SVG generation.
     */
    function buildSvgPrompt(content, userQuery, lang) {
        return `Generate an SVG illustration for the following content.

Rules:
1. Output ONLY valid SVG code — no explanation, no markdown fences
2. Use ${lang} text labels
3. Use a clean, modern style with a white/light background
4. Size: viewBox="0 0 800 500"
5. Use colors that are professional and readable
6. Include a brief title in the SVG
7. Use proper SVG text elements, not foreignObject
${userQuery ? `\nUser's request: ${userQuery}` : ''}

Content:\n${content.substring(0, 5000)}`;
    }

    /**
     * Call LLM to generate diagram code.
     * Returns { type: string, code: string }
     */
    async function generate(content, options = {}) {
        const {
            diagramType = 'auto',
            userQuery = '',
            language = 'en',
        } = options;

        const { type, prompt } = buildDiagramPrompt(content, diagramType, userQuery, language);

        const { text } = await LLMClient.chat([
            { role: 'system', content: 'You are a diagram generation expert. Output ONLY diagram code — no explanation, no markdown fences, no ```.' },
            { role: 'user', content: prompt },
        ], { stream: false, maxTokens: 2000, temperature: 0.3 });

        // Strip markdown fences if LLM added them
        const code = (text || '').trim()
            .replace(/^```(?:mermaid|svg|xml)?\s*\n?/i, '')
            .replace(/\n?```\s*$/i, '')
            .trim();

        return { type, code };
    }

    /**
     * Render Mermaid code using the sandboxed iframe.
     * Returns a Promise<string> with rendered SVG HTML.
     */
    function renderMermaid(mermaidCode) {
        return new Promise((resolve, reject) => {
            const iframe = document.getElementById('mermaidSandbox');
            if (!iframe) {
                reject(new Error('Mermaid sandbox not found'));
                return;
            }

            const timeoutId = setTimeout(() => {
                reject(new Error('Mermaid rendering timed out'));
            }, 15000);

            function onMessage(event) {
                if (event.data && event.data.type === 'mermaid-result') {
                    clearTimeout(timeoutId);
                    window.removeEventListener('message', onMessage);
                    if (event.data.error) {
                        reject(new Error(event.data.error));
                    } else {
                        resolve(event.data.svg);
                    }
                }
            }

            window.addEventListener('message', onMessage);
            iframe.contentWindow.postMessage({
                type: 'render-mermaid',
                code: mermaidCode,
            }, '*');
        });
    }

    /**
     * Generate and render a diagram.
     * Returns { type, code, svg }
     */
    async function generateAndRender(content, options = {}) {
        const { type, code } = await generate(content, options);

        let svg;
        if (type === 'svg') {
            // SVG is already renderable
            svg = code;
        } else {
            // Render Mermaid
            svg = await renderMermaid(code);
        }

        return { type, code, svg };
    }

    /**
     * Build a self-contained HTML export of a diagram.
     */
    function exportAsHtml(title, svgContent, mermaidCode, sourceContent) {
        return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<title>${escHtml(title)}</title>
<style>
body { font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif; margin: 0; padding: 20px; background: #f8f9fa; }
.container { max-width: 900px; margin: 0 auto; }
h1 { font-size: 18px; color: #333; margin-bottom: 16px; }
.diagram-box { background: #fff; border: 1px solid #e0e0e0; border-radius: 10px; padding: 20px; margin-bottom: 16px; text-align: center; overflow: auto; }
.diagram-box svg { max-width: 100%; height: auto; }
.code-box { background: #263238; color: #eeffff; border-radius: 8px; padding: 14px 18px; font-family: 'Fira Code', monospace; font-size: 12px; white-space: pre-wrap; overflow-x: auto; margin-bottom: 16px; }
.source { background: #fff; border: 1px solid #e0e0e0; border-radius: 10px; padding: 16px; font-size: 13px; color: #555; line-height: 1.6; max-height: 300px; overflow-y: auto; }
.label { font-size: 11px; color: #999; font-weight: 600; text-transform: uppercase; letter-spacing: 0.5px; margin-bottom: 6px; }
</style>
</head>
<body>
<div class="container">
    <h1>${escHtml(title)}</h1>
    <div class="diagram-box">${svgContent}</div>
    ${mermaidCode ? `<div class="label">Mermaid Code</div><div class="code-box">${escHtml(mermaidCode)}</div>` : ''}
    ${sourceContent ? `<div class="label">Source Content</div><div class="source">${escHtml(sourceContent).substring(0, 2000)}</div>` : ''}
</div>
</body>
</html>`;
    }

    function escHtml(s) {
        return (s || '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
    }

    return {
        DIAGRAM_TYPES, detectDiagramType,
        generate, renderMermaid, generateAndRender,
        exportAsHtml,
    };
})();
